FakeBackend _backend() {
  final b = baseBackend();
  b.get('/procurement/dashboard', {'openAlerts': {'CRITICAL': 1, 'LOW': 1}, 'pendingApproval': 1, 'awaitingSupplier': 0, 'inTransit': 0, 'deliveredNotReceived': 0, 'monthToDateSpend': 42244.53});
  b.on('GET', '/procurement/purchase-orders', (o) {
    final statuses = o.queryParameters['status'] as List;
    return page(statuses.contains('PENDING_APPROVAL') ? [_po('PENDING_APPROVAL')] : const []);
  });
  b.get('/procurement/purchase-orders/po1', _po('PENDING_APPROVAL'));
  b.get('/procurement/alerts', [
    {
      'id': 'al1',
      'outletId': 'o1',
