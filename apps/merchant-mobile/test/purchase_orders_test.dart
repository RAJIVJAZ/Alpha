Future<void> _openPurchasing(WidgetTester tester) async {
  await openTab(tester, 'More');
  await tester.tap(find.text('Purchasing'));
  await tester.pumpAndSettle();
}

void main() {
  testWidgets('the owner approves a purchase order with a comment', (tester) async {
    final backend = _backend();
    backend.post('/procurement/purchase-orders/po1/approve', _po('SENT_TO_SUPPLIER'));
    await pumpMerchantApp(tester, backend);
    await _openPurchasing(tester);

    expect(backend.callsTo('GET', '/procurement/purchase-orders').first.queryParameters['status'], ['DRAFT', 'PENDING_APPROVAL', 'REJECTED']);
    expect(find.text('PO-261007-00001'), findsOneWidget);
    expect(find.text('Cowberry Dairy Distributors'), findsOneWidget);

    await tester.tap(find.text('PO-261007-00001'));
    await tester.pumpAndSettle();
    expect(find.text('Set Curd 5 kg Bucket'), findsOneWidget);
    expect(find.text('₹1,417.50'), findsWidgets);

    await tester.tap(find.widgetWithText(FilledButton, 'Approve & send'));
    await tester.pumpAndSettle();
    expect(find.text('Approve PO-261007-00001?'), findsOneWidget);
    await tester.enterText(find.widgetWithText(TextField, 'Comment (optional)'), 'Curd needed for the weekend');
    await tester.tap(find.widgetWithText(FilledButton, 'Approve & send').last);
    await tester.pumpAndSettle();

    expect(backend.lastBody('POST', '/procurement/purchase-orders/po1/approve'), {'comment': 'Curd needed for the weekend'});
    expect(find.text('PO-261007-00001: sent to supplier'), findsOneWidget);
    expect(backend.callsTo('GET', '/procurement/purchase-orders/po1').length, greaterThanOrEqualTo(2)); // reloaded
  });

  testWidgets('a manager sees the PO but cannot approve it', (tester) async {
    await pumpMerchantApp(tester, _backend(), accessToken: merchantToken(role: 'MANAGER'));
    await _openPurchasing(tester);
    await tester.tap(find.text('PO-261007-00001'));
    await tester.pumpAndSettle();

    expect(find.text('Approve & send'), findsNothing);
    expect(find.text('Only the owner can approve purchase orders.'), findsOneWidget);
    expect(find.text('Cancel PO'), findsOneWidget); // procurement:manage
  });

  testWidgets('reorder alerts list for the outlet; kitchen roles have no purchasing', (tester) async {
    final backend = _backend();
    await pumpMerchantApp(tester, backend);
    await _openPurchasing(tester);
    await tester.tap(find.text('Alerts'));
    await tester.pumpAndSettle();

    expect(find.text('Tomato'), findsOneWidget);
    expect(find.text('Critical'), findsOneWidget);
    expect(find.text('15.18 kg'), findsOneWidget);
    expect(backend.callsTo('GET', '/procurement/alerts').last.queryParameters['outletId'], 'o1');
  });

  testWidgets('chefs do not get the purchasing screen', (tester) async {
    await pumpMerchantApp(tester, _backend(), accessToken: merchantToken(role: 'CHEF'));
    await openTab(tester, 'More');
    expect(find.text('Purchasing'), findsNothing);
    expect(find.text("Today's sales"), findsNothing);
    expect(find.text('Inventory'), findsOneWidget);
  });
}
