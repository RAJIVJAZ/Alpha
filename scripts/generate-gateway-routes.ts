/**
 * Derives the API gateway routing table from the generated OpenAPI specs
 * (docs/api/*.json — run `pnpm docs:openapi` first), so routing always
 * matches the routes the services actually expose.
 *
 *   pnpm gateway:routes
 *
 * Writes:
 *   infrastructure/gateway/routes.json     consumed by scripts/dev-gateway.ts and Helm
 *   infrastructure/docker/nginx/gateway.conf   nginx config for docker-compose
 *   vercel.json                            the six web apps on Vercel (one project, routed by subdomain)
 *   infrastructure/railway/*               the API services and the gateway on Railway
 *   packages/auth/src/next/api-routes.ts   which service owns an API path (web apps on Vercel)
 *
 * A first path segment owned by several services (e.g. /admin) is split on
 * its second segment; any prefix still claimed twice fails the build.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(__dirname, '..');
const API_DIR = path.join(root, 'docs', 'api');

export const SERVICE_PORTS: Record<string, number> = {
  'auth-service': 4001,
  'user-service': 4002,
  'order-service': 4003,
  'payment-service': 4004,
  'inventory-service': 4005,
  'procurement-service': 4006,
  'delivery-service': 4007,
  'supplier-service': 4008,
  'analytics-service': 4009,
  'ads-service': 4010,
  'notification-service': 4011,
  'ai-service': 4012,
};

/** Web apps and the subdomain each one answers on (same hosts as the Kubernetes ingress). */
const WEB_APPS: Record<string, string | null> = {
  'admin-web': 'admin',
  'restaurant-web': 'partner',
  'vendor-web': 'business',
  'supplier-web': 'supplier',
  'rider-web': 'rider',
  'customer-web': null, // every other host: foodgrid.in, www., api. and preview URLs
};

interface Route {
  prefix: string;
  service: string;
  websocket?: boolean;
}

function main() {
  const owners = new Map<string, Set<string>>();
  const claim = (prefix: string, service: string) =>
    owners.set(prefix, (owners.get(prefix) ?? new Set()).add(service));
  const paths = new Map<string, string[]>();
  for (const file of readdirSync(API_DIR).filter((f) => f.endsWith('-service.json'))) {
    const service = file.replace(/\.json$/, '');
    paths.set(
      service,
      Object.keys(
        (JSON.parse(readFileSync(path.join(API_DIR, file), 'utf8')) as { paths: object }).paths,
      ),
    );
  }
  // first pass: first segment after /api/v1
  for (const [service, list] of paths) {
    for (const p of list) {
      const segs = p.split('/').filter(Boolean);
      if (segs[0] !== 'api') claim(`/${segs.join('/')}`, service);
      else if (segs[2] && segs[2] !== 'internal') claim(`/api/v1/${segs[2]}`, service);
    }
  }
  // shared first segments are routed on their second segment
  const shared = [...owners].filter(([, s]) => s.size > 1).map(([p]) => p);
  for (const prefix of shared) {
    owners.delete(prefix);
    for (const [service, list] of paths) {
      for (const p of list) {
        if (!p.startsWith(`${prefix}/`)) continue;
        const next = p.slice(prefix.length + 1).split('/')[0]!;
        claim(`${prefix}/${next}`, service);
      }
    }
  }
  const conflicts = [...owners].filter(([, s]) => s.size > 1);
  if (conflicts.length) {
    throw new Error(
      `Ambiguous gateway prefixes:\n${conflicts.map(([p, s]) => `  ${p}: ${[...s].join(', ')}`).join('\n')}`,
    );
  }
  const routes: Route[] = [...owners].map(([prefix, s]) => ({ prefix, service: [...s][0]! }));
  routes.push({ prefix: '/ws', service: 'delivery-service', websocket: true });
  routes.sort((a, b) => b.prefix.length - a.prefix.length || a.prefix.localeCompare(b.prefix));

  const table = {
    $comment:
      'Generated by scripts/generate-gateway-routes.ts from docs/api — do not edit by hand.',
    blocked: ['/api/v1/internal'],
    services: Object.fromEntries(
      Object.entries(SERVICE_PORTS).map(([name, port]) => [name, { port }]),
    ),
    routes,
  };
  writeFileSync(
    path.join(root, 'infrastructure', 'gateway', 'routes.json'),
    `${JSON.stringify(table, null, 2)}\n`,
  );
  writeFileSync(
    path.join(root, 'infrastructure', 'docker', 'nginx', 'gateway.conf'),
    nginx(routes),
  );
  writeFileSync(path.join(root, 'vercel.json'), `${JSON.stringify(vercel(), null, 2)}\n`);
  railway();
  writeFileSync(
    path.join(root, 'packages', 'auth', 'src', 'next', 'api-routes.ts'),
    `// Generated by scripts/generate-gateway-routes.ts from docs/api — do not edit by hand.
/** API path prefix (longest first) → the env var holding the owning service's URL. */
export const API_ROUTES: readonly (readonly [prefix: string, env: string])[] = [
${routes
  .filter((r) => !r.websocket)
  .map((r) => `  ['${r.prefix}', '${envOf(r.service)}'],`)
  .join('\n')}
];
`,
  );
  console.log(
    `Gateway: ${routes.length} routes across ${new Set(routes.map((r) => r.service)).size} services`,
  );
}

/** auth-service → AUTH_SERVICE_URL (InternalHttpService and the web apps read these). */
const envOf = (service: string) => `${service.replace(/-service$/, '').toUpperCase()}_SERVICE_URL`;

/**
 * One Vercel project for the six web apps, picked by subdomain. They reach the API through
 * API_URL (the Railway gateway); the API services need long-running processes, so they
 * run on Railway, not on Vercel.
 */
function vercel() {
  const services = Object.fromEntries(
    Object.keys(WEB_APPS).map((app) => [
      app,
      {
        root: `apps/${app}`,
        framework: 'nextjs',
        buildCommand: `cd ../.. && pnpm turbo run build --filter=@foodgrid/${app}...`,
      },
    ]),
  );
  const rewrites = Object.entries(WEB_APPS)
    .sort(([, a], [, b]) => (a === null ? 1 : 0) - (b === null ? 1 : 0))
    .map(([app, sub]) => ({
      source: '/(.*)',
      ...(sub ? { has: [{ type: 'host', value: `${sub}\\..+` }] } : {}),
      destination: { service: app },
    }));
  return { $schema: 'https://openapi.vercel.sh/vercel.json', services, rewrites };
}

/**
 * Railway config as code: one file per API service plus the gateway (point each Railway
 * service's config path at its file), and the private-network service URLs to paste into
 * the project's shared variables. Each API service also needs PORT set to its port below.
 */
function railway() {
  const dir = path.join(root, 'infrastructure', 'railway');
  mkdirSync(dir, { recursive: true });
  const write = (name: string, config: object) =>
    writeFileSync(
      path.join(dir, `${name}.json`),
      `${JSON.stringify({ $schema: 'https://railway.com/railway.schema.json', ...config }, null, 2)}\n`,
    );
  for (const svc of Object.keys(SERVICE_PORTS)) {
    write(svc, {
      build: {
        builder: 'RAILPACK',
        buildCommand: `pnpm turbo run build --filter=@foodgrid/${svc}...`,
        watchPatterns: [
          `services/${svc}/**`,
          'packages/**',
          'pnpm-lock.yaml',
          `infrastructure/railway/${svc}.json`,
        ],
      },
      deploy: {
        // migrate deploy is idempotent and takes a database lock, so every service can run it
        // first; the lock wait gives up after 10 s, so the first deploy's waiters retry
        preDeployCommand: ['pnpm --filter @foodgrid/database db:deploy:retry'],
        // NODE_ENV only at runtime: set at build time it would skip the dev dependencies the build needs
        startCommand: `env NODE_ENV=production node services/${svc}/dist/main.js`,
        healthcheckPath: '/health/ready',
        restartPolicyType: 'ON_FAILURE',
      },
    });
  }
  write('gateway', {
    build: {
      builder: 'RAILPACK',
      buildCommand: 'echo "the gateway runs from source"',
      watchPatterns: [
        'scripts/dev-gateway.ts',
        'infrastructure/gateway/routes.json',
        'infrastructure/railway/gateway.json',
      ],
    },
    deploy: {
      startCommand: 'pnpm exec tsx scripts/dev-gateway.ts',
      healthcheckPath: '/healthz',
      restartPolicyType: 'ON_FAILURE',
    },
  });
  writeFileSync(
    path.join(dir, 'service-urls.env'),
    `${Object.entries(SERVICE_PORTS)
      .map(([svc, port]) => `${envOf(svc)}=http://${svc}.railway.internal:${port}`)
      .join('\n')}\n`,
  );
}

function nginx(routes: Route[]): string {
  const upstreams = Object.entries(SERVICE_PORTS).map(
    ([name, port]) =>
      `upstream ${name.replace(/-/g, '_')} {\n  server ${name}:${port};\n  keepalive 32;\n}`,
  );
  const locations = routes.map((r) => {
    const up = r.service.replace(/-/g, '_');
    const exact = r.prefix.includes('.well-known');
    const loc = exact ? `location = ${r.prefix}` : `location ^~ ${r.prefix}`;
    const ws = r.websocket
      ? '\n    proxy_set_header Upgrade $http_upgrade;\n    proxy_set_header Connection $connection_upgrade;\n    proxy_read_timeout 1h;'
      : '';
    return `  ${loc} {\n    proxy_pass http://${up};${ws}\n  }`;
  });
  return `# Generated by scripts/generate-gateway-routes.ts from docs/api — do not edit by hand.
${upstreams.join('\n\n')}

map $http_upgrade $connection_upgrade {
  default upgrade;
  ''      close;
}

limit_req_zone $binary_remote_addr zone=auth:10m rate=10r/m;
limit_req_zone $binary_remote_addr zone=api:10m rate=30r/s;

server {
  listen 8080;
  client_max_body_size 10m;

  proxy_http_version 1.1;
  proxy_set_header Connection "";
  proxy_set_header Host $host;
  proxy_set_header X-Real-IP $remote_addr;
  proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
  proxy_set_header X-Forwarded-Proto $scheme;
  proxy_set_header X-Request-Id $request_id;
  add_header X-Request-Id $request_id always;

  # service-to-service routes are never reachable from outside
  location ^~ /api/v1/internal { return 404; }

  location = /healthz { return 200 "ok\\n"; }

  # OTP and password login are rate limited per client IP
  location ~ ^/api/v1/auth/(otp/request|password)$ {
    limit_req zone=auth burst=5 nodelay;
    proxy_pass http://auth_service;
  }

${locations.join('\n\n')}

  location / { return 404; }
}
`;
}

main();
